from ortools.sat.python import cp_model
model = cp_model.CpModel()
Ali = model.NewIntVar(1, 6, "Ali")
Sara = model.NewIntVar(1, 6, "Sara")
Ahmed = model.NewIntVar(1, 6, "Ahmed")
Zoya = model.NewIntVar(1, 6, "Zoya")
Bilal = model.NewIntVar(2, 6, "Bilal")
Hina = model.NewIntVar(2, 6, "Hina")
model.AddAllDifferent([Ali, Sara, Ahmed, Zoya, Bilal, Hina])
model.AddAbsEquality(model.NewIntVar(0, 5, "SaraZoyaDiff"), Sara - Zoya)
model.AddAbsEquality(model.NewIntVar(0, 5, "AliAhmedDiff"), Ali - Ahmed)
model.AddAllowedAssignments([Bilal], [(2,), (4,), (6,)])
model.Add(Hina != 1)
model.Add(Sara - Zoya == 1)
model.Add(Ali - Ahmed != 1)
model.Add(Ahmed - Ali != 1)

solver = cp_model.CpSolver()
status = solver.Solve(model)
if status == cp_model.OPTIMAL or status == cp_model.FEASIBLE:
    print("Seating Arrangement:")
    print("Ali:", solver.Value(Ali))
    print("Sara:", solver.Value(Sara))
    print("Ahmed:", solver.Value(Ahmed))
    print("Zoya:", solver.Value(Zoya))
    print("Bilal:", solver.Value(Bilal))
    print("Hina:", solver.Value(Hina))
else:
    print("No solution found")